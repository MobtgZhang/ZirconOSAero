const IconPixels = [16][16]u4;
const IconPalette = [9]u32;

/// 与 `IconId` 数值 1..=32 一一对应（`drawAeroIcon` 内嵌位图）。
const icon_embedded_count: usize = 32;

// ── Helper: draw any 16×16 indexed-color icon ──

fn drawPixelIcon(
    id: IconId,
    screen_x: i32,
    screen_y: i32,
    scale: u32,
    palettes: *const [icon_embedded_count]IconPalette,
    pixels: *const [icon_embedded_count]IconPixels,
) void {
    const v = @intFromEnum(id);
    if (v < 1 or v > icon_embedded_count) return;
    const idx: usize = @intCast(v - 1);
    const data = &pixels[idx];
    const palette = &palettes[idx];
    const s: i32 = if (scale < 1) 1 else @intCast(scale);

    for (data, 0..) |row, dy| {
        for (row, 0..) |cidx, dx| {
            if (cidx == 0) continue;
            const color = palette[@intCast(cidx)];
            const px64 = @as(i64, screen_x) + @as(i64, @intCast(dx)) * @as(i64, s);
            const py64 = @as(i64, screen_y) + @as(i64, @intCast(dy)) * @as(i64, s);
            const px = clampIconCoordToI32(px64);
            const py = clampIconCoordToI32(py64);
            if (s == 1) {
                if (px >= 0 and py >= 0) fb.putPixel32(@intCast(px), @intCast(py), color);
            } else {
                fb.fillRect(px, py, s, s, color);
            }
        }
    }
}
