fn clampIconCoordToI32(v: i64) i32 {
    return @intCast(std.math.clamp(v, @as(i64, std.math.minInt(i32)), @as(i64, std.math.maxInt(i32))));
}

fn rgb(r: u32, g: u32, b: u32) u32 {
    return b | (g << 8) | (r << 16);
}

