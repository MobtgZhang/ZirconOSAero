//! Aero 箭头光标位图（与 `src/desktop/dwm/compositor/` 中光标定义一致）。
//! 内核帧缓冲路径不加载 SVG，仅使用此数组绘制；修改形状时请与 DWM 库同步。
//! 其它形态为壳层命中测试用近似（与 `resources/cursors/*.svg` 语义对应，非 SVG 渲染）。
//!
//! 编码：0=透明，1=填充，2=描边，3=玻璃高光，4=内发光

pub const W: usize = 14;
pub const H: usize = 20;

pub const CursorKind = enum(u8) {
    arrow,
    /// 文本/地址栏（`zircon_text.svg`）
    ibeam,
    /// 链接/菜单项：当前与箭头同形（`zircon_link.svg` 的占位）
    hand,
    /// 拖动窗口（`zircon_move.svg`）
    move,
    /// 等待（`zircon_busy.svg` 简化沙漏）
    busy,
};

pub fn pixels(kind: CursorKind) *const [H][W]u3 {
    return switch (kind) {
        .arrow, .hand => &shape,
        .ibeam => &shape_ibeam,
        .move => &shape_move,
        .busy => &shape_busy,
    };
}

